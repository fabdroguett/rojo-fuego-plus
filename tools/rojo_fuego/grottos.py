#!/usr/bin/env python3
"""Rojo Fuego+ daily hidden grottos (from Pokémon SoulGold).

Each grotto takes the place of one hidden item on a Kanto route: the spot becomes a sign-type
event that, once a day, holds a rare Pokémon (always with its hidden ability) or an item. The
grotto's daily flag is cleared by ClearDailyFlags, and the Key System's hidden-item sparkle also
marks grottos that are still unused today (src/key_system.c).

    python3 tools/rojo_fuego/grottos.py
writes data/scripts/rojo_fuego_grottos.inc, src/data/rf_grottos.h and edits the route map.json
files (only the first time: a spot already turned into a grotto is left as it is).
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
MAPS = ROOT / "data/maps"
SCRIPTS = ROOT / "data/scripts/rojo_fuego_grottos.inc"
TABLE = ROOT / "src/data/rf_grottos.h"

# route map -> (level, three species)
GROTTOS = [
    ("Route3_Frlg", 15, ["RIOLU", "EEVEE", "BAGON"]),
    ("Route6_Frlg", 20, ["ABRA", "DRATINI", "PORYGON"]),
    ("Route8_Frlg", 25, ["GROWLITHE", "VULPIX", "LITWICK"]),
    ("Route9_Frlg", 25, ["LARVITAR", "GIBLE", "AXEW"]),
    ("Route12_Frlg", 30, ["CHANSEY", "SNORLAX", "TOGEPI"]),
    ("Route14_Frlg", 30, ["SCYTHER", "PINSIR", "HERACROSS"]),
    ("Route17_Frlg", 35, ["TYROGUE", "DEINO", "GOOMY"]),
    ("Route25_Frlg", 35, ["JANGMO_O", "FRIGIBAX", "DREEPY"]),
]

ITEMS = ["ITEM_BIG_PEARL", "ITEM_STAR_PIECE", "ITEM_RARE_CANDY", "ITEM_PP_UP",
         "ITEM_BOTTLE_CAP", "ITEM_ABILITY_CAPSULE", "ITEM_NUGGET", "ITEM_HEART_SCALE"]


def script_label(i):
    return f"RF_EventScript_Grotto_{i}"


def place_grottos():
    for i, (map_name, _, _) in enumerate(GROTTOS):
        path = MAPS / map_name / "map.json"
        data = json.loads(path.read_text(encoding="utf-8"))
        events = data["bg_events"]
        if any(e.get("script") == script_label(i) for e in events):
            continue
        for index, event in enumerate(events):
            if event["type"] == "hidden_item":
                events[index] = {
                    "type": "sign",
                    "x": event["x"],
                    "y": event["y"],
                    "elevation": event["elevation"],
                    "player_facing_dir": "BG_EVENT_PLAYER_FACING_ANY",
                    "script": script_label(i),
                }
                break
        else:
            raise SystemExit(f"no hidden item left on {map_name}")
        path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def write_scripts():
    out = ["@ Rojo Fuego+ daily hidden grottos. Generated by tools/rojo_fuego/grottos.py; do not edit.\n"]
    for i, (_, level, species) in enumerate(GROTTOS):
        label = script_label(i)
        out.append(f"""
	.global {label}
{label}::
	lock
	goto_if_set FLAG_RF_GROTTO_{i}, RF_EventScript_Grotto_Empty
	msgbox RF_Text_Grotto_Found
	setflag FLAG_RF_GROTTO_{i}
	random 10
	goto_if_ge VAR_RESULT, 6, RF_EventScript_Grotto_Item
	random 3
	goto_if_eq VAR_RESULT, 0, {label}_Mon0
	goto_if_eq VAR_RESULT, 1, {label}_Mon1
	goto {label}_Mon2
""")
        for n, mon in enumerate(species):
            out.append(f"""{label}_Mon{n}:
	setwildbattle SPECIES_{mon}, {level}
	goto RF_EventScript_Grotto_Battle
""")
    out.append("""
RF_EventScript_Grotto_Battle::
	callnative Script_SetWildMonHiddenAbility
	msgbox RF_Text_Grotto_Pokemon
	closemessage
	dowildbattle
	release
	end

RF_EventScript_Grotto_Item::
	random 8
""")
    for n, item in enumerate(ITEMS[:-1]):
        out.append(f"\tgoto_if_eq VAR_RESULT, {n}, RF_EventScript_Grotto_Item{n}\n")
    out.append(f"\tgoto RF_EventScript_Grotto_Item{len(ITEMS) - 1}\n")
    for n, item in enumerate(ITEMS):
        out.append(f"""RF_EventScript_Grotto_Item{n}:
	finditem {item}
	release
	end
""")
    out.append("""
RF_EventScript_Grotto_Empty::
	msgbox RF_Text_Grotto_Empty
	release
	end

RF_Text_Grotto_Found:
	.string "¡Entre la maleza hay un claro\\n"
	.string "escondido!$"

RF_Text_Grotto_Pokemon:
	.string "¡Un Pokémon poco común descansaba\\n"
	.string "en el claro!$"

RF_Text_Grotto_Empty:
	.string "Un claro escondido… Hoy no hay\\n"
	.string "nada. Vuelve mañana.$"
""")
    SCRIPTS.write_text("".join(out), encoding="utf-8")


def write_table():
    lines = ["// Generated by tools/rojo_fuego/grottos.py; do not edit.\n",
             "// Grotto scripts and their daily flags, for the hidden-item sparkle.\n\n"]
    lines += [f"extern const u8 {script_label(i)}[];\n" for i in range(len(GROTTOS))]
    lines.append("\nstatic const struct { const u8 *script; u16 flag; } sRfGrottos[] =\n{\n")
    lines += [f"    {{{script_label(i)}, FLAG_RF_GROTTO_{i}}},\n" for i in range(len(GROTTOS))]
    lines.append("};\n")
    TABLE.write_text("".join(lines), encoding="utf-8")


if __name__ == "__main__":
    place_grottos()
    write_scripts()
    write_table()
    print(f"{len(GROTTOS)} grottos")
