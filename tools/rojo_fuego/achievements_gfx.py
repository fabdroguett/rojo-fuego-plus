#!/usr/bin/env python3
# Draws the achievements screen background (styled after the trophy screen in Pokémon SoulGold)
# and writes it as C arrays: 4bpp tiles, a 32x32 tilemap and the BG palette.
#   python3 tools/rojo_fuego/achievements_gfx.py   ->  src/data/rf_achievements_gfx.h
# Also writes a preview PNG next to this script.
import os, struct, zlib

W, H = 240, 160
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'src', 'data', 'rf_achievements_gfx.h')

def rgb(h):
    return ((h >> 16) & 0xFF, (h >> 8) & 0xFF, h & 0xFF)

PAL = [rgb(c) for c in [
    0xF0E6BC,  # 0 background
    0xE6D9A4,  # 1 background stripe
    0xD86A20,  # 2 header
    0x8C3C0C,  # 3 header shadow
    0xF59C48,  # 4 header highlight
    0xFFFBEA,  # 5 panel fill
    0xC8B068,  # 6 panel border
    0x7C6A30,  # 7 panel border dark
    0x283860,  # 8 description box
    0x4A5E98,  # 9 description border
    0x98B0E0,  # 10 description border light
    0xEEE2B4,  # 11 panel inner shade
    0x000000, 0x000000, 0x000000, 0x000000,
]]

img = [[0] * W for _ in range(H)]

def fill(x0, y0, x1, y1, c):
    for y in range(max(0, y0), min(H, y1)):
        for x in range(max(0, x0), min(W, x1)):
            img[y][x] = c

# Background with soft diagonal stripes
for y in range(H):
    for x in range(W):
        img[y][x] = 1 if (x + y) % 16 < 3 else 0

# Header bar
fill(0, 0, W, 16, 2)
fill(0, 0, W, 1, 4)
fill(0, 14, W, 16, 3)

def panel(x0, y0, x1, y1):
    # Rounded box: dark outline, light border, fill, with a soft inner shade on top
    fill(x0 + 2, y0, x1 - 2, y1, 7)
    fill(x0, y0 + 2, x1, y1 - 2, 7)
    fill(x0 + 1, y0 + 1, x1 - 1, y1 - 1, 7)
    fill(x0 + 2, y0 + 1, x1 - 2, y1 - 1, 6)
    fill(x0 + 1, y0 + 2, x1 - 1, y1 - 2, 6)
    fill(x0 + 3, y0 + 3, x1 - 3, y1 - 3, 5)
    fill(x0 + 3, y0 + 3, x1 - 3, y0 + 4, 11)

panel(6, 20, 166, 108)    # achievement list
panel(170, 20, 236, 108)  # status column

# Description box
fill(0, 112, W, H, 8)
fill(0, 112, W, 113, 10)
fill(0, 113, W, 114, 9)

# Convert to deduplicated 4bpp tiles + tilemap
tiles, index, tilemap = [], {}, [0] * (32 * 32)
for ty in range(H // 8):
    for tx in range(W // 8):
        data = bytearray()
        for y in range(8):
            row = img[ty * 8 + y][tx * 8:tx * 8 + 8]
            for x in range(0, 8, 2):
                data.append(row[x] | (row[x + 1] << 4))
        key = bytes(data)
        if key not in index:
            index[key] = len(tiles)
            tiles.append(key)
        tilemap[ty * 32 + tx] = index[key]

def gba(c):
    r, g, b = c
    return (r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10)

# Palette of the text windows (BG palette 1). The trophy colors match ACH_TIER_* order.
TEXT_PAL = [rgb(c) for c in [
    0x000000,  # 0 transparent
    0xFFFFFF,  # 1 white
    0x383838,  # 2 dark text
    0xCCC4A4,  # 3 shadow on light panels
    0x101828,  # 4 shadow on the dark box and header
    0xFFE68C,  # 5 selected row
    0x20903A,  # 6 green (reward ready)
    0xD48446, 0x80401A,  # 7-8 bronze
    0xD8D8E6, 0x6E6E88,  # 9-10 silver
    0xF8D030, 0xA07808,  # 11-12 gold
    0x98E4F8, 0x3488B0,  # 13-14 platinum
    0xA8A8A8,  # 15 locked
]]

TROPHY = [
    "................",
    "...DDDDDDDDDD...",
    ".DDDWMMMMMMMDDD.",
    "D..DWMMMMMMMD..D",
    "D..DWMMMMMMMD..D",
    ".D.DMMMMMMMMD.D.",
    "..DDMMMMMMMMDD..",
    "....DMMMMMMD....",
    ".....DMMMMD.....",
    "......DMMD......",
    "......DMMD......",
    ".....DMMMMD.....",
    "....DDDDDDDD....",
    "....DMMMMMMD....",
    "....DDDDDDDD....",
    "................",
]

# (main, dark) per icon: bronze, silver, gold, platinum, locked
ICON_COLORS = [(7, 8), (9, 10), (11, 12), (13, 14), (3, 15)]

def icon_tiles(main, dark):
    px = [[{'.': 0, 'D': dark, 'M': main, 'W': 1}[ch] for ch in row] for row in TROPHY]
    data = bytearray()
    for ty in range(2):
        for tx in range(2):
            for y in range(8):
                row = px[ty * 8 + y][tx * 8:tx * 8 + 8]
                for x in range(0, 8, 2):
                    data.append(row[x] | (row[x + 1] << 4))
    return data

with open(OUT, 'w') as f:
    f.write('// Generated by tools/rojo_fuego/achievements_gfx.py; do not edit.\n')
    f.write('// Achievements screen background: %d tiles.\n\n' % len(tiles))
    words = []
    for t in tiles:
        words += struct.unpack('<8I', t)
    f.write('static const u32 sAchScreenTiles[] =\n{\n')
    for i in range(0, len(words), 8):
        f.write('    ' + ', '.join('0x%08X' % w for w in words[i:i + 8]) + ',\n')
    f.write('};\n\nstatic const u16 sAchScreenTilemap[32 * 32] =\n{\n')
    for i in range(0, len(tilemap), 16):
        f.write('    ' + ', '.join('0x%04X' % t for t in tilemap[i:i + 16]) + ',\n')
    f.write('};\n\nstatic const u16 sAchScreenBgPal[16] =\n{\n')
    f.write('    ' + ', '.join('0x%04X' % gba(c) for c in PAL) + ',\n};\n')
    f.write('\nstatic const u16 sAchScreenTextPal[16] =\n{\n')
    f.write('    ' + ', '.join('0x%04X' % gba(c) for c in TEXT_PAL) + ',\n};\n')
    f.write('\n// 16x16 trophies in tile order: bronze, silver, gold, platinum, locked\n')
    f.write('static const u8 sAchTrophyIcons[5][128] =\n{\n')
    for main, dark in ICON_COLORS:
        data = icon_tiles(main, dark)
        f.write('    {\n')
        for i in range(0, 128, 16):
            f.write('        ' + ', '.join('0x%02X' % b for b in data[i:i + 16]) + ',\n')
        f.write('    },\n')
    f.write('};\n')

# Preview
def png(path, pixels, w, h):
    raw = b''.join(b'\x00' + bytes(v for x in range(w) for v in PAL[pixels[y][x]]) for y in range(h))
    def chunk(t, d):
        return struct.pack('>I', len(d)) + t + d + struct.pack('>I', zlib.crc32(t + d) & 0xFFFFFFFF)
    open(path, 'wb').write(b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 2, 0, 0, 0))
                           + chunk(b'IDAT', zlib.compress(raw)) + chunk(b'IEND', b''))

png(os.path.join(HERE, 'achievements_bg_preview.png'), img, W, H)
print('tiles:', len(tiles))
