"""Generate src/data/rf_menu_icons.h from graphics/rojo_fuego/icons/kenney_1bit_menu.png.

The PNG holds 16x16 tiles from Kenney's 1-Bit Pack (CC0, see CREDITS.md). Each tile becomes
a 1-bit mask (16 rows, bit 15 = leftmost pixel); RFUI_DrawIcon paints it with theme roles at
runtime, so one mask serves dark, light and selected states. The Poke Ball is our own drawing.
Standard library only: python tools/rojo_fuego/make_menu_icons.py
"""
from pathlib import Path
import struct
import zlib

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "graphics/rojo_fuego/icons/kenney_1bit_menu.png"
OUTPUT = ROOT / "src/data/rf_menu_icons.h"
ENUM_OUTPUT = ROOT / "include/constants/rf_menu_icons.h"
# Order of tiles in the PNG, with their Kenney 1-Bit Pack sheet index for provenance.
KENNEY = [
    ("POKEDEX", 290, "book"),
    ("BAG", 241, "backpack"),
    ("DEXNAV", 576, "scanner"),
    ("PROFILE", 827, "person"),
    ("SAVE", 826, "floppy disk"),
    ("OPTIONS", 829, "gear"),
    ("EXIT", 1060, "arrow back"),
    ("KEY", 571, "key"),
    ("QUESTS", 768, "scroll"),
]
BALL = """
................
.....######.....
...##########...
..############..
.##############.
.######..######.
.#####.##.#####.
#.....#..#.....#
#.....#..#.....#
.#.....##.....#.
.#............#.
..#..........#..
...#........#...
....##....##....
......####......
................
"""


def read_rgba(path):
    data = path.read_bytes()
    assert data[:8] == b"\x89PNG\r\n\x1a\n"
    pos, idat, width = 8, b"", 0
    while pos < len(data):
        length, kind = struct.unpack(">I4s", data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + length]
        if kind == b"IHDR":
            width, height, depth, color, _, _, interlace = struct.unpack(">IIBBBBB", body)
            assert (depth, color, interlace) == (8, 6, 0), "expected 8-bit RGBA, non-interlaced"
        elif kind == b"IDAT":
            idat += body
        pos += 12 + length
    raw, stride, rows, prev = zlib.decompress(idat), width * 4, [], bytearray(width * 4)
    for y in range(height):
        kind, line = raw[y * (stride + 1)], bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        for x in range(stride):
            a = line[x - 4] if x >= 4 else 0
            b, c = prev[x], prev[x - 4] if x >= 4 else 0
            if kind == 1:
                line[x] = (line[x] + a) & 255
            elif kind == 2:
                line[x] = (line[x] + b) & 255
            elif kind == 3:
                line[x] = (line[x] + (a + b) // 2) & 255
            elif kind == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[x] = (line[x] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        rows.append(line)
        prev = line
    return width, rows


def main():
    width, rows = read_rgba(SOURCE)
    assert width == 16 * len(KENNEY)
    masks = []
    for k, (name, index, label) in enumerate(KENNEY):
        mask = [sum(1 << (15 - x) for x in range(16) if rows[y][(k * 16 + x) * 4 + 3] >= 128) for y in range(16)]
        masks.append((name, f"Kenney 1-Bit Pack #{index}: {label}", mask))
    ball = [line for line in BALL.split() if line]
    masks.insert(1, ("TEAM", "Rojo Fuego Plus original: Poke Ball",
                     [sum(1 << (15 - x) for x, ch in enumerate(line) if ch == "#") for line in ball]))
    header = "// Generated by tools/rojo_fuego/make_menu_icons.py. Do not edit by hand."
    enum = [header, "#ifndef GUARD_CONSTANTS_RF_MENU_ICONS_H", "#define GUARD_CONSTANTS_RF_MENU_ICONS_H", "",
            "enum RFMenuIcon", "{"]
    enum += [f"    RF_ICON_{name}," for name, _, _ in masks] + ["    RF_ICON_COUNT", "};", "", "#endif"]
    ENUM_OUTPUT.write_text("\n".join(enum) + "\n", encoding="utf-8")
    out = [header,
           "// 16x16 1-bit masks, bit 15 = leftmost pixel. Kenney 1-Bit Pack is CC0 (kenney.nl).",
           "static const u16 sRFMenuIconMasks[RF_ICON_COUNT][16] =", "{"]
    for name, credit, mask in masks:
        out.append(f"    [RF_ICON_{name}] = {{ // {credit}")
        for i in range(0, 16, 8):
            out.append("        " + ", ".join(f"0x{v:04X}" for v in mask[i:i + 8]) + ",")
        out.append("    },")
    out.append("};")
    OUTPUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{OUTPUT.relative_to(ROOT)}: {len(masks)} icons")


if __name__ == "__main__":
    import sys
    if "--legacy-reference" in sys.argv:
        main()
    else:
        from make_kanto_ui_art import main as build_native
        build_native()
