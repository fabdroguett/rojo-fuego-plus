#!/usr/bin/env python3
# Rebuilds the DexNav screen background with Spanish labels.
#   python3 tools/rojo_fuego/dexnav_gui.py render   -> writes the current screen as dexnav_screen.png (for reference)
#   python3 tools/rojo_fuego/dexnav_gui.py build    -> repaints the labels and rewrites gui_tiles.png + gui_tilemap.bin
# The original English sheet is kept as graphics/dexnav/gui_tiles_en.png / gui_tilemap_en.bin.
import os, shutil, struct, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pngutil

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
GFX = os.path.join(ROOT, 'graphics', 'dexnav')
TILES, TILEMAP = os.path.join(GFX, 'gui_tiles.png'), os.path.join(GFX, 'gui_tilemap.bin')
TILES_EN, TILEMAP_EN = os.path.join(GFX, 'gui_tiles_en.png'), os.path.join(GFX, 'gui_tilemap_en.bin')
W, H = 240, 160

def render():
    w, h, pal, px = pngutil.read_png(TILES_EN)
    tiles_per_row = w // 8
    tilemap = struct.unpack('<1024H', open(TILEMAP_EN, 'rb').read())
    img = [[0] * W for _ in range(H)]
    for ty in range(H // 8):
        for tx in range(W // 8):
            e = tilemap[ty * 32 + tx]
            t, hf, vf = e & 0x3FF, (e >> 10) & 1, (e >> 11) & 1
            sx, sy = (t % tiles_per_row) * 8, (t // tiles_per_row) * 8
            for y in range(8):
                for x in range(8):
                    yy, xx = (7 - y) if vf else y, (7 - x) if hf else x
                    img[ty * 8 + y][tx * 8 + x] = px[sy + yy][sx + xx]
    return pal, img

# Tab areas the game draws the "caught/total" counter into (dexnav.c, DrawAreaCounters):
# name, first tile column, tile row, width and height in tiles, y of the text inside the area
COUNTERS = [
    ('WATER',  12, 1,  4, 2, 6),
    ('LAND',   14, 6,  4, 2, 7),
    ('HIDDEN',  9, 14, 4, 2, 8),
]
COUNTER_HEADER = os.path.join(ROOT, 'src', 'data', 'dexnav_counter_tiles.h')

def retile(pal, img):
    tiles, index, tilemap = [], {}, [0] * 1024
    reserved = {}
    for name, cx, cy, cw, ch, _ in COUNTERS:
        for y in range(ch):
            for x in range(cw):
                reserved[(cx + x, cy + y)] = name
    counter_tiles = {name: [] for name, *_ in COUNTERS}
    for ty in range(H // 8):
        for tx in range(W // 8):
            key = tuple(tuple(img[ty * 8 + y][tx * 8:tx * 8 + 8]) for y in range(8))
            if (tx, ty) in reserved:
                # Its own copy, since the game draws on it
                counter_tiles[reserved[(tx, ty)]].append(len(tiles))
                tilemap[ty * 32 + tx] = len(tiles)
                tiles.append(key)
                continue
            if key not in index:
                index[key] = len(tiles)
                tiles.append(key)
            tilemap[ty * 32 + tx] = index[key]
    with open(COUNTER_HEADER, 'w') as f:
        f.write('// Generated by tools/rojo_fuego/dexnav_gui.py; do not edit.\n')
        f.write('// BG1 tiles of the DexNav tab areas that show the caught/total counter (row-major).\n\n')
        f.write('#define DEXNAV_COUNTER_WIDTH  %d\n#define DEXNAV_COUNTER_HEIGHT %d\n\n' % (COUNTERS[0][3], COUNTERS[0][4]))
        f.write('static const struct DexNavCounterArea sDexNavCounterAreas[] =\n{\n')
        for name, cx, cy, cw, ch, text_y in COUNTERS:
            f.write('    [COUNTER_%s] = {.textY = %d, .tiles = {%s}},\n' % (name, text_y, ', '.join(str(t) for t in counter_tiles[name])))
        f.write('};\n')
    per_row = 16
    rows = (len(tiles) + per_row - 1) // per_row
    sheet = [[0] * (per_row * 8) for _ in range(rows * 8)]
    for i, t in enumerate(tiles):
        ox, oy = (i % per_row) * 8, (i // per_row) * 8
        for y in range(8):
            sheet[oy + y][ox:ox + 8] = list(t[y])
    pngutil.write_png(TILES, pal, sheet)
    open(TILEMAP, 'wb').write(struct.pack('<1024H', *tilemap))
    return len(tiles)

