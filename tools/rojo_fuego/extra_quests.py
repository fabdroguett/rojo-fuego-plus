#!/usr/bin/env python3
"""Generate the 279 post-saga field missions (stable IDs 71–349)."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
FIRST_ID = 71
TARGET = 350
COLLECT_ITEMS = [
    ("ITEM_POTION", "Poción"), ("ITEM_GREAT_BALL", "Super Ball"), ("ITEM_ETHER", "Éter"),
    ("ITEM_PARALYZE_HEAL", "Antiparalizador"), ("ITEM_ESCAPE_ROPE", "Cuerda Huida"),
    ("ITEM_REPEL", "Repelente"), ("ITEM_REVIVE", "Revivir"),
    ("ITEM_SUPER_POTION", "Superpoción"), ("ITEM_HYPER_POTION", "Hiperpoción"),
    ("ITEM_FULL_HEAL", "Restau. Todo"),
]
USE_ITEMS = [
    ("ITEM_POKE_BALL", "Poké Ball"), ("ITEM_POTION", "Poción"), ("ITEM_REPEL", "Repelente"),
    ("ITEM_ESCAPE_ROPE", "Cuerda Huida"), ("ITEM_HYPER_POTION", "Hiperpoción"),
    ("ITEM_REVIVE", "Revivir"), ("ITEM_FULL_HEAL", "Restau. Todo"), ("ITEM_ETHER", "Éter"),
    ("ITEM_SUPER_REPEL", "Superrepelente"), ("ITEM_MAX_POTION", "Máxima Poción"),
]


def species_catalog():
    text = (ROOT / "include/constants/species.h").read_text(encoding="utf-8")
    return [(int(value), name.removeprefix("SPECIES_"))
            for name, value in re.findall(r"\b(SPECIES_[A-Z0-9_]+)\s*=\s*(\d+)", text)
            if int(value) > 0 and int(value) < 1000][:TARGET - FIRST_ID]


def validate_species_reachability(species):
    """Every Dex target must be catchable, obtainable through evolution, or in the legend roster."""
    encounters = (ROOT / "src/data/wild_encounters.json").read_text(encoding="utf-8")
    reachable = set(re.findall(r"SPECIES_[A-Z0-9_]+", encounters))
    legend_data = (ROOT / "src/data/rf_legends.h").read_text(encoding="utf-8")
    reachable.update(re.findall(r"\{(SPECIES_[A-Z0-9_]+), RF_QUEST_LEGEND_", legend_data))
    for script in (ROOT / "data/maps").glob("*/scripts.inc"):
        source = script.read_text(encoding="utf-8")
        reachable.update(re.findall(r"\bsetwildbattle\s+(SPECIES_[A-Z0-9_]+)", source))
    evolutions = {}
    for path in (ROOT / "src/data/pokemon/species_info").glob("gen_*_families.h"):
        text = path.read_text(encoding="utf-8")
        blocks = re.split(r"(?=^\s*\[SPECIES_[A-Z0-9_]+\]\s*=\s*\{)", text, flags=re.M)
        for block in blocks:
            source = re.match(r"\s*\[(SPECIES_[A-Z0-9_]+)\]", block)
            evolution = re.search(r"\.evolutions\s*=\s*EVOLUTION\((.*?)\),", block, re.S)
            if source and evolution:
                evolutions[source.group(1)] = set(re.findall(r"SPECIES_[A-Z0-9_]+", evolution.group(1)))
    while True:
        expanded = reachable | {target for source, targets in evolutions.items()
                                if source in reachable for target in targets}
        if expanded == reachable:
            break
        reachable = expanded
    missing = [f"SPECIES_{name}" for _, name in species if f"SPECIES_{name}" not in reachable]
    if missing:
        raise SystemExit("Dex missions target species with no encounter/evolution/legend route: "
                         + ", ".join(missing))


def main():
    species = species_catalog()
    if len(species) != TARGET - FIRST_ID:
        raise SystemExit(f"Need 279 species entries; found {len(species)}")
    validate_species_reachability(species)
    constants = ["// Generated by tools/rojo_fuego/extra_quests.py; IDs are stable."]
    entries = ["// Generated by tools/rojo_fuego/extra_quests.py. Included inside sRFQuests[]."]
    for offset, (species_id, symbol) in enumerate(species):
        quest_id = FIRST_ID + offset
        name = symbol.replace("_", " ").title()
        # Species symbols are unique and fit the quest panel title limit.
        if len(name) > 40:
            raise SystemExit(f"quest title too long: {name}")
        previous = "RF_QUEST_REMATCH_REPORT" if offset == 0 else f"RF_QUEST_EXTRA_{offset - 1:03d}"
        constant = f"RF_QUEST_EXTRA_{offset:03d}"
        constants.append(f"#define {constant} {quest_id}")
        condition = "QUEST_DEX_CAUGHT"
        argument = f"SPECIES_{symbol}"
        alternative = ""
        objective_fields = ""
        if 250 <= offset < 260:
            item, item_name = COLLECT_ITEMS[offset - 250]
            condition, argument = "QUEST_COLLECT_ITEM", item
            name = f"Suministro: {item_name}"
            description = f"Guarda {item_name} en la mochila\npara el laboratorio de Oak."
        elif 260 <= offset < 270:
            item, item_name = USE_ITEMS[offset - 260]
            condition, argument = "QUEST_USE_ITEM", item
            name = f"Práctica: {item_name}"
            use_descriptions = [
                "Lanza una Poké Ball en un combate.",
                "Usa una Poción con un Pokémon.\nEl efecto debe aplicarse.",
                "Activa un Repelente en una ruta.",
                "Usa una Cuerda Huida en una cueva.",
                "Recupera PS con una Hiperpoción.",
                "Reanima a un Pokémon debilitado.",
                "Cura un problema de estado.",
                "Recupera PP con un Éter.",
                "Activa un Superrepelente en ruta.",
                "Recupera PS con una Máxima\nPoción.",
            ]
            description = use_descriptions[offset - 260]
        elif offset >= 270:
            partner = ("SPECIES_BULBASAUR", "Bulbasaur") if offset % 3 == 0 else (
                ("SPECIES_CHARMANDER", "Charmander") if offset % 3 == 1 else ("SPECIES_SQUIRTLE", "Squirtle"))
            description = f"Registra a {name} y lleva a\n{partner[1]} en tu equipo."
            objective_fields = (
                f"        .objectiveCount = 2, .secondaryCondition = QUEST_PARTY_EITHER,\n"
                f"        .secondaryArgument = {partner[0]}, .secondaryAlternative = SPECIES_NONE,\n"
            )
        else:
            description = f"Captura a {name} y registra su\nficha en la Pokédex de campo."
        if any(len(line) > 40 for line in description.splitlines()):
            raise SystemExit(f"description too long: {name}")
        reward = ("ITEM_POKE_BALL", 2) if offset % 3 else ("ITEM_GREAT_BALL", 1)
        chapter = 3 + (offset // 47) % 3
        description_c = description.replace("\n", "\\n")
        entries += [
            f"    [{constant}] = {{",
            f'        .name = COMPOUND_STRING("Registro: {name}"),',
            f'        .description = COMPOUND_STRING("{description_c}"),',
            f"        .prerequisite = {previous}, .condition = {condition},",
            f"        .argument = {argument}, .rewardItem = {reward[0]}, .rewardCount = {reward[1]}, .chapter = {chapter},",
            *(objective_fields.rstrip("\n").split("\n") if objective_fields else []),
            "    },",
        ]
    (ROOT / "include/constants/rf_quests_extra.h").write_text("\n".join(constants) + "\n", encoding="utf-8")
    (ROOT / "src/data/rf_quests_extra.h").write_text("\n".join(entries) + "\n", encoding="utf-8")
    print(f"Generated {TARGET - FIRST_ID} field missions: 259 Pokédex, 10 collection, "
          f"10 successful-use, 9 multi-objective ({FIRST_ID}–{TARGET - 1}).")


if __name__ == "__main__":
    main()
